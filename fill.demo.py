def fill_data():
    print("🚀 Начинаем заполнение базы демо-данными...")

    # 1. Категории
    cat_objects = {}
    for name, desc in CATEGORIES:
        cat, created = Category.objects.get_or_create(
            name=name, 
            defaults={'description': desc}
        )
        cat_objects[name] = cat
        status = "✅ Создана" if created else "🔁 Пропущена (существует)"
        print(f"   Категория '{name}': {status}")

    # 2. Товары
    prod_count = 0
    for name, desc, price, cat_name in PRODUCTS:
        category = cat_objects.get(cat_name)
        if category:
            prod, created = Product.objects.get_or_create(
                name=name,
                defaults={
                    'description': desc,
                    'price': price,
                    'category': category,
                    'status': 'active'
                }
            )
            if created:
                # 3. Остатки на складе
                Stock.objects.create(product=prod, quantity=10, reserved=0, min_threshold=5)
                prod_count += 1
                print(f"   📦 Товар '{name}' добавлен.")

    print("-" * 30)
    print(f"✅ Готово! Добавлено {prod_count} новых товаров с остатками.")
    print("👤 Таблица пользователей не затрагивалась.")
    print("💡 Не забудь создать админа: python manage.py createsuperuser")

if __name__ == "__main__":
    fill_data()